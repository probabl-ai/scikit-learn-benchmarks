"""
Download the ephemeral `results/` tree a PR-comparison run deployed to its
Cloudflare Pages preview site (see COMPARISONS_PR.md /
.github/workflows/pr-comparison.yml) into a local `results/` directory, so
dashboards can be regenerated locally against them.

Those results are never committed to this repo (each push re-triggers the
comparison and overwrites the previous deploy), and the site has no
directory listing, so there's no way to just mirror it wholesale. Instead
this fetches `pr_comparison.html` (always generated by
dashboards/pr_comparison_dashboard.py) and scrapes it for every
`results/records/*.json` link it embeds via `json_url_fn` -
`detailed_results_table_html` (sklbench/reporting/html/table.py) links one
JSON per individual record row (base, variant, failed, and unmatched
results all included), not a deduped/aggregated view, so this recovers the
full raw record set. Each downloaded record is then read for its
`hardware_hash`/`software_hash` to fetch the matching
`results/hardware-envs/<hash>.json` and `results/software-envs/<hash>.json`
- more reliable than scraping those from dashboard HTML, since some
dashboards (e.g. gen_hgb_dev_scalability_breakdown.py) link software-envs
via a GitHub-raw-URL fallback that 404s for these never-committed results
rather than the hosted site.

A `sklbench-compare` directive's `runs:` entries can target either
self-hosted runner (see COMPARISONS_PR.md), each getting its own CI job and
its own site (`pr-<n>-compare-<runner>...`) - so by default this fetches
every runner's site for the given PR and merges them into the same local
`results/` dir (that's what `gen_*.py` dashboards expect: one dir covering
all hardware, distinguished by `hardware_hash`). A runner a PR's directive
didn't target simply has no deployed site and is skipped with a warning
rather than failing the whole run.

Usage:

    pixi run -e reporting python scripts/fetch_pr_results.py --pr 74
    pixi run -e reporting python scripts/fetch_pr_results.py --pr 74 --runner intel-gnr
    pixi run -e reporting python scripts/fetch_pr_results.py \\
        --site-url https://pr-74-compare-intel-gnr.sklbench-pr-comparison.pages.dev
"""

import argparse
import json
from pathlib import Path
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

SITE_URL_TEMPLATE = "https://pr-{pr}-compare-{runner}.sklbench-pr-comparison.pages.dev"
VALID_RUNNERS = ("intel-laptop", "intel-gnr")


def _fetch(url: str) -> bytes | None:
    # Cloudflare Pages 403s urllib's default "Python-urllib/x.y" user agent.
    request = urllib.request.Request(url, headers={"User-Agent": "sklbench-fetch-pr-results"})
    try:
        with urllib.request.urlopen(request) as response:
            return response.read()
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return None
        raise


def _save(dest: Path, data: bytes, *, force: bool) -> bool:
    if dest.exists() and not force:
        return False
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return True


def find_record_names(pr_comparison_html: bytes, site_url: str) -> list[str]:
    # json_url_fn/profile_url_fn wrap the hosted URL in a viewer's `?url=`
    # query string, percent-encoding it - decoding the whole page once lets
    # one plain-text regex match both that and any unencoded occurrence.
    decoded = urllib.parse.unquote(pr_comparison_html.decode("utf-8"))
    prefix = f"{site_url}/results/records/"
    pattern = re.escape(prefix) + r"([^\"'\s<>]+\.json)"
    return sorted(set(re.findall(pattern, decoded)))


def fetch_site(site_url: str, results_dir: Path, *, force: bool) -> tuple[int, int] | None:
    """Returns (downloaded, skipped), or None if this site has no deployed
    comparison (e.g. a PR whose directive didn't target this runner)."""
    site_url = site_url.rstrip("/")
    pr_comparison_html = _fetch(f"{site_url}/pr_comparison.html")
    if pr_comparison_html is None:
        return None

    record_names = find_record_names(pr_comparison_html, site_url)
    if not record_names:
        print(f"warning: no results/records/*.json links found in {site_url}/pr_comparison.html", file=sys.stderr)
        return (0, 0)

    hashes: dict[str, set[str]] = {"hardware-envs": set(), "software-envs": set()}
    downloaded = skipped = 0
    for name in record_names:
        dest = results_dir / "records" / name
        if dest.exists() and not force:
            skipped += 1
        else:
            data = _fetch(f"{site_url}/results/records/{name}")
            if data is None:
                print(f"warning: 404 fetching records/{name}", file=sys.stderr)
                continue
            _save(dest, data, force=force)
            downloaded += 1
        # Read hashes from disk either way, so a record downloaded on a
        # previous run still gets its env files fetched this time.
        record = json.loads(dest.read_bytes())
        if record.get("hardware_hash"):
            hashes["hardware-envs"].add(record["hardware_hash"])
        if record.get("software_hash"):
            hashes["software-envs"].add(record["software_hash"])

    for kind, hash_set in hashes.items():
        for env_hash in sorted(hash_set):
            dest = results_dir / kind / f"{env_hash}.json"
            if dest.exists() and not force:
                continue
            data = _fetch(f"{site_url}/results/{kind}/{env_hash}.json")
            if data is None:
                print(f"warning: 404 fetching {kind}/{env_hash}.json", file=sys.stderr)
                continue
            if _save(dest, data, force=force):
                downloaded += 1

    return (downloaded, skipped)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    site = parser.add_mutually_exclusive_group(required=True)
    site.add_argument("--site-url", help="Base URL of one deployed PR-comparison site")
    site.add_argument("--pr", type=int, help="PR number (fetches every runner's site unless --runner is given)")
    parser.add_argument(
        "--runner",
        choices=VALID_RUNNERS,
        help="Restrict --pr to one self-hosted runner (default: fetch all runners)",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=Path("results"),
        help="Local results directory to write into (default: ./results)",
    )
    parser.add_argument(
        "--force", action="store_true", help="Re-download and overwrite files that already exist locally"
    )
    args = parser.parse_args()

    if args.site_url is not None:
        sites = [args.site_url]
    else:
        runners = [args.runner] if args.runner else list(VALID_RUNNERS)
        sites = [SITE_URL_TEMPLATE.format(pr=args.pr, runner=runner) for runner in runners]

    total_downloaded = total_skipped = 0
    any_found = False
    for site_url in sites:
        result = fetch_site(site_url, args.results_dir, force=args.force)
        if result is None:
            print(f"warning: no deployed site at {site_url} (runner not targeted by this PR?)", file=sys.stderr)
            continue
        any_found = True
        downloaded, skipped = result
        total_downloaded += downloaded
        total_skipped += skipped
        print(f"{site_url}: downloaded {downloaded}, {skipped} already present")

    if not any_found:
        print("error: no deployed site found for any requested runner", file=sys.stderr)
        return 1

    print(f"Total: downloaded {total_downloaded} file(s), {total_skipped} record(s) already present, "
          f"into {args.results_dir}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
